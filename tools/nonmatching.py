#!/usr/bin/env python3
"""
Near misses (docs/contributing/nonmatching.md): nonmatching/<area>/func_X.c and the table
in nonmatching/README.md. Ported from rac1-decomp.

  python3 tools/nonmatching.py readme
      Rewrites nonmatching/README.md from the files.
  python3 tools/nonmatching.py stage func_X=path/to/candidate.c "VERDICT" ...
      Stores each candidate as func_X's near miss (with a first-line comment
      giving the verdict), unless the one already there is as close, and
      rewrites the README.
  python3 tools/nonmatching.py drop func_X ...
      Removes near misses (the function matched) and rewrites the README.

The first line of every file is a comment saying what still differs:
  /* Not matching yet: BYTES 5/64 (tools/try_func.py func_X --diff). Not part of the build. */
`readme` copies it into the table; `stage` compares its BYTES with the new one.
"""
from __future__ import annotations
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import layout  # noqa: E402

ROOT = layout.ROOT
DIR = ROOT / "nonmatching"


def staged() -> dict[str, Path]:
    return {p.stem: p for p in sorted(DIR.glob("*/func_*.c"))}


def note(path: Path) -> str:
    first = path.read_text(errors="replace").splitlines()[0] if path.stat().st_size else ""
    if not first.startswith("/* Not matching yet"):
        return "not recorded"
    what = first[len("/* Not matching yet"):].replace("*/", "").replace("Not part of the build.", "")
    what = re.sub(r"\((?:see )?tools/\w+\.py[^)]*\)", "", what)
    return what.strip(" .:") or "not recorded"


def miss(verdict: str) -> float | None:
    """Fraction of the bytes that differ, from a BYTES n/size verdict."""
    m = re.search(r"BYTES (\d+)/(\d+)", verdict)
    return int(m.group(1)) / int(m.group(2)) if m else None


def readme() -> None:
    rows = []
    for name, path in staged().items():
        size = layout.catalogue().get(name, {}).get("size", 0)
        what = note(path)
        rows.append((miss(what) if miss(what) is not None else 2.0, name, path, size, what))
    out = ["# Near misses", "",
           "Best attempts at functions that do not match yet. They are not built; see",
           "[docs/contributing/nonmatching.md](../docs/contributing/nonmatching.md). Generated by `tools/nonmatching.py`.", "",
           "| Function | Directory | Size | What differs |", "|---|---|---|---|"]
    for _, name, path, size, what in sorted(rows):
        rel = path.relative_to(DIR)
        out.append(f"| [`{name}`]({rel.as_posix()}) | {rel.parent.as_posix()} | {size} | {what} |")
    (DIR / "README.md").write_text("\n".join(out) + "\n")


def stage(name: str, candidate: Path, verdict: str) -> bool:
    dst = layout.nonmatching_path(name)
    if dst.exists():
        old, new = miss(note(dst)), miss(verdict)
        if new is None or (old is not None and old <= new):
            return False
    body = candidate.read_text(errors="replace").rstrip("\n")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(f"/* Not matching yet: {verdict} (tools/try_func.py {name} --diff). "
                   f"Not part of the build. */\n{body}\n")
    return True


def drop(name: str) -> bool:
    path = staged().get(name)
    if path is None:
        return False
    path.unlink()
    if not any(path.parent.iterdir()):
        path.parent.rmdir()
    return True


def main() -> None:
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)
    cmd, rest = args[0], args[1:]
    if cmd == "stage" and rest and len(rest) % 2 == 0:
        for job, verdict in zip(rest[::2], rest[1::2]):
            name, _, path = job.partition("=")
            print(f"{name} {'staged' if stage(name, ROOT / path, verdict) else 'kept (staged one is as close)'}")
    elif cmd == "drop" and rest:
        for name in rest:
            print(f"{name} {'dropped' if drop(name) else 'not staged'}")
    elif cmd != "readme":
        sys.exit(__doc__)
    readme()


if __name__ == "__main__":
    main()
